/** Validate that every supported language covers every key of the English base. */
export function validateDictionaries() {
  const baseKeys = Object.keys(DICTIONARIES[DEFAULT_LANG]).sort();
  const missing = {};
  for (const lang of SUPPORTED_LANGS) {
    const keys = Object.keys(DICTIONARIES[lang]).sort();
    missing[lang] = baseKeys.filter((k) => !keys.includes(k));
  }
  return missing;
}
